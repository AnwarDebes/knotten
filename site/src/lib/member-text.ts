/** The privacy notice with the link word in place (CONTACT_NOTICE from lib/consent ends with that word). */
export function splitNotice(notice: string, word: string): [string, string, string] {
  const at = notice.lastIndexOf(word);
  return at >= 0 ? [notice.slice(0, at), word, notice.slice(at + word.length)] : [`${notice} `, word, ""];
}
